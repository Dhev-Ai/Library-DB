@router.get("/tables")
def get_tables_list():
    tables_data = []
    for t_name in ALLOWED_TABLES:
        meta = TABLE_SCHEMAS.get(t_name, {})
        # Get live row count
        count_res = db_manager.query(f"SELECT COUNT(*) AS cnt FROM {t_name}", fetch_one=True)
        cnt = count_res["cnt"] if count_res else 0
        tables_data.append({
            "table_name": t_name,
            "row_count": cnt,
            "description": meta.get("description", ""),
            "primary_key": meta.get("pk", []),
            "foreign_keys": meta.get("fks", []),
            "column_count": len(meta.get("columns", []))
        })
    return {
        "database_engine": db_manager.engine_type,
        "database_name": "library_lending_db",
        "tables": tables_data
    }

@router.get("/tables/{table_name}")
def get_table_details(
    table_name: str,
    page: int = Query(1, ge=1),
    limit: int = Query(10, ge=1, le=100)
):
    table_upper = table_name.upper()
    if table_upper not in ALLOWED_TABLES:
        raise HTTPException(status_code=404, detail="Table not found in allowlist")

    meta = TABLE_SCHEMAS.get(table_upper, {})
    offset = (page - 1) * limit

    # Count
    count_res = db_manager.query(f"SELECT COUNT(*) AS cnt FROM {table_upper}", fetch_one=True)
    total_count = count_res["cnt"] if count_res else 0

    # Data preview - hide raw password column if table is ADMIN
    if table_upper == "ADMIN":
        preview_sql = f"SELECT admin_id, username, '•••••••• [Protected]' AS password FROM ADMIN LIMIT %s OFFSET %s"
    else:
        preview_sql = f"SELECT * FROM {table_upper} LIMIT %s OFFSET %s"

    rows = db_manager.query(preview_sql, (limit, offset))
    # Normalize strings for any date/decimal fields
    clean_rows = []
    for r in rows:
        clean_r = {}
        for k, v in r.items():
            if isinstance(v, (bytes, bytearray)):
                clean_r[k] = "[Binary]"
            else:
                clean_r[k] = str(v) if v is not None else None
        clean_rows.append(clean_r)

    return {
        "table_name": table_upper,
        "metadata": meta,
        "total_rows": total_count,
        "page": page,
        "limit": limit,
        "total_pages": (total_count + limit - 1) // limit if limit > 0 else 1,
        "rows": clean_rows
    }
