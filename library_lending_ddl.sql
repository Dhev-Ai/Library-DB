-- =============================================================================
-- Library Lending Management System - Phase 2 Database Implementation
-- DDL Script: Database Creation, Tables, Keys, Constraints & Indexes
-- Standard: MySQL 8.0+ / MariaDB 10.5+
-- Schema normalized up to 3NF based on Phase 1 System Design
-- =============================================================================

DROP DATABASE IF EXISTS library_lending_db;
CREATE DATABASE library_lending_db 
    CHARACTER SET utf8mb4 
    COLLATE utf8mb4_unicode_ci;

USE library_lending_db;

-- =============================================================================
-- TABLE 1: PERSON (Superclass for STUDENT and ADMIN)
-- =============================================================================
CREATE TABLE PERSON (
    person_id INT AUTO_INCREMENT,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(120) NOT NULL UNIQUE,
    CONSTRAINT pk_person PRIMARY KEY (person_id),
    CONSTRAINT chk_person_email CHECK (email LIKE '%_@__%.__%')
) ENGINE=InnoDB;

-- =============================================================================
-- TABLE 2: PERSON_PHONE (1NF Multi-valued Phone Decomposition)
-- =============================================================================
CREATE TABLE PERSON_PHONE (
    person_id INT NOT NULL,
    phone_number VARCHAR(20) NOT NULL,
    CONSTRAINT pk_person_phone PRIMARY KEY (person_id, phone_number),
    CONSTRAINT fk_person_phone_person FOREIGN KEY (person_id) 
        REFERENCES PERSON(person_id) 
        ON DELETE CASCADE 
        ON UPDATE CASCADE
) ENGINE=InnoDB;

-- =============================================================================
-- TABLE 3: STUDENT (Subclass of PERSON)
-- =============================================================================
CREATE TABLE STUDENT (
    student_id INT NOT NULL,
    department VARCHAR(80) NOT NULL,
    join_year YEAR NOT NULL,
    CONSTRAINT pk_student PRIMARY KEY (student_id),
    CONSTRAINT fk_student_person FOREIGN KEY (student_id) 
        REFERENCES PERSON(person_id) 
        ON DELETE CASCADE 
        ON UPDATE CASCADE,
    CONSTRAINT chk_student_year CHECK (join_year >= 1990)
) ENGINE=InnoDB;

-- =============================================================================
-- TABLE 4: UNDERGRADUATE (Subclass of STUDENT)
-- Borrow Limit fixed to 3 books per specifications
-- =============================================================================
CREATE TABLE UNDERGRADUATE (
    student_id INT NOT NULL,
    borrow_limit INT NOT NULL DEFAULT 3,
    CONSTRAINT pk_undergraduate PRIMARY KEY (student_id),
    CONSTRAINT fk_undergraduate_student FOREIGN KEY (student_id) 
        REFERENCES STUDENT(student_id) 
        ON DELETE CASCADE 
        ON UPDATE CASCADE,
    CONSTRAINT chk_ug_borrow_limit CHECK (borrow_limit = 3)
) ENGINE=InnoDB;

-- =============================================================================
-- TABLE 5: POSTGRADUATE (Subclass of STUDENT)
-- Borrow Limit fixed to 6 books per specifications
-- =============================================================================
CREATE TABLE POSTGRADUATE (
    student_id INT NOT NULL,
    borrow_limit INT NOT NULL DEFAULT 6,
    research_area VARCHAR(150) NOT NULL,
    CONSTRAINT pk_postgraduate PRIMARY KEY (student_id),
    CONSTRAINT fk_postgraduate_student FOREIGN KEY (student_id) 
        REFERENCES STUDENT(student_id) 
        ON DELETE CASCADE 
        ON UPDATE CASCADE,
    CONSTRAINT chk_pg_borrow_limit CHECK (borrow_limit = 6)
) ENGINE=InnoDB;

-- =============================================================================
-- TABLE 6: ADMIN (Subclass of PERSON - Library Staff)
-- =============================================================================
CREATE TABLE ADMIN (
    admin_id INT NOT NULL,
    username VARCHAR(50) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    CONSTRAINT pk_admin PRIMARY KEY (admin_id),
    CONSTRAINT fk_admin_person FOREIGN KEY (admin_id) 
        REFERENCES PERSON(person_id) 
        ON DELETE CASCADE 
        ON UPDATE CASCADE
) ENGINE=InnoDB;

-- =============================================================================
-- TABLE 7: REPORT (System & Library Analytics generated by Admins)
-- =============================================================================
CREATE TABLE REPORT (
    report_id INT AUTO_INCREMENT,
    report_type VARCHAR(60) NOT NULL,
    generated_date DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    admin_id INT NOT NULL,
    CONSTRAINT pk_report PRIMARY KEY (report_id),
    CONSTRAINT fk_report_admin FOREIGN KEY (admin_id) 
        REFERENCES ADMIN(admin_id) 
        ON DELETE RESTRICT 
        ON UPDATE CASCADE
) ENGINE=InnoDB;

-- =============================================================================
-- TABLE 8: CATEGORY (3NF separation from BOOK to remove Transitive Dependency)
-- =============================================================================
CREATE TABLE CATEGORY (
    category_id INT AUTO_INCREMENT,
    category_name VARCHAR(100) NOT NULL UNIQUE,
    CONSTRAINT pk_category PRIMARY KEY (category_id)
) ENGINE=InnoDB;

-- =============================================================================
-- TABLE 9: BOOK (Core Entity Catalog)
-- =============================================================================
CREATE TABLE BOOK (
    book_id INT AUTO_INCREMENT,
    title VARCHAR(200) NOT NULL,
    isbn VARCHAR(20) NOT NULL UNIQUE,
    author VARCHAR(150) NOT NULL,
    copies_available INT NOT NULL DEFAULT 1,
    category_id INT NOT NULL,
    CONSTRAINT pk_book PRIMARY KEY (book_id),
    CONSTRAINT fk_book_category FOREIGN KEY (category_id) 
        REFERENCES CATEGORY(category_id) 
        ON DELETE RESTRICT 
        ON UPDATE CASCADE,
    CONSTRAINT chk_book_copies CHECK (copies_available >= 0)
) ENGINE=InnoDB;

-- =============================================================================
-- TABLE 10: TEXTBOOK (Subclass of BOOK)
-- =============================================================================
CREATE TABLE TEXTBOOK (
    book_id INT NOT NULL,
    edition VARCHAR(30) NOT NULL,
    CONSTRAINT pk_textbook PRIMARY KEY (book_id),
    CONSTRAINT fk_textbook_book FOREIGN KEY (book_id) 
        REFERENCES BOOK(book_id) 
        ON DELETE CASCADE 
        ON UPDATE CASCADE
) ENGINE=InnoDB;

-- =============================================================================
-- TABLE 11: REFERENCE_BOOK (Subclass of BOOK - In-library reading only)
-- =============================================================================
CREATE TABLE REFERENCE_BOOK (
    book_id INT NOT NULL,
    lendable ENUM('No', 'Yes') NOT NULL DEFAULT 'No',
    CONSTRAINT pk_reference_book PRIMARY KEY (book_id),
    CONSTRAINT fk_reference_book_book FOREIGN KEY (book_id) 
        REFERENCES BOOK(book_id) 
        ON DELETE CASCADE 
        ON UPDATE CASCADE,
    CONSTRAINT chk_ref_lendable CHECK (lendable = 'No')
) ENGINE=InnoDB;

-- =============================================================================
-- TABLE 12: JOURNAL (Subclass of BOOK)
-- =============================================================================
CREATE TABLE JOURNAL (
    book_id INT NOT NULL,
    issue_no INT NOT NULL,
    volume_no INT NOT NULL,
    CONSTRAINT pk_journal PRIMARY KEY (book_id),
    CONSTRAINT fk_journal_book FOREIGN KEY (book_id) 
        REFERENCES BOOK(book_id) 
        ON DELETE CASCADE 
        ON UPDATE CASCADE
) ENGINE=InnoDB;

-- =============================================================================
-- TABLE 13: RESERVES (M:N Reservation between Student and Book)
-- =============================================================================
CREATE TABLE RESERVES (
    student_id INT NOT NULL,
    book_id INT NOT NULL,
    reserve_date DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_reserves PRIMARY KEY (student_id, book_id),
    CONSTRAINT fk_reserves_student FOREIGN KEY (student_id) 
        REFERENCES STUDENT(student_id) 
        ON DELETE CASCADE 
        ON UPDATE CASCADE,
    CONSTRAINT fk_reserves_book FOREIGN KEY (book_id) 
        REFERENCES BOOK(book_id) 
        ON DELETE CASCADE 
        ON UPDATE CASCADE
) ENGINE=InnoDB;

-- =============================================================================
-- TABLE 14: LENDING_RECORD (Circulation Transactions)
-- =============================================================================
CREATE TABLE LENDING_RECORD (
    lending_id INT AUTO_INCREMENT,
    issue_date DATE NOT NULL,
    due_date DATE NOT NULL,
    return_date DATE NULL,
    status ENUM('Issued', 'Returned', 'Overdue', 'Damaged', 'Lost') NOT NULL DEFAULT 'Issued',
    student_id INT NOT NULL,
    book_id INT NOT NULL,
    admin_id INT NOT NULL,
    CONSTRAINT pk_lending_record PRIMARY KEY (lending_id),
    CONSTRAINT fk_lending_student FOREIGN KEY (student_id) 
        REFERENCES STUDENT(student_id) 
        ON DELETE RESTRICT 
        ON UPDATE CASCADE,
    CONSTRAINT fk_lending_book FOREIGN KEY (book_id) 
        REFERENCES BOOK(book_id) 
        ON DELETE RESTRICT 
        ON UPDATE CASCADE,
    CONSTRAINT fk_lending_admin FOREIGN KEY (admin_id) 
        REFERENCES ADMIN(admin_id) 
        ON DELETE RESTRICT 
        ON UPDATE CASCADE,
    CONSTRAINT chk_due_date CHECK (due_date >= issue_date),
    CONSTRAINT chk_return_date CHECK (return_date IS NULL OR return_date >= issue_date)
) ENGINE=InnoDB;

-- =============================================================================
-- TABLE 15: FINE (General Fine Record 1:1 with LENDING_RECORD)
-- =============================================================================
CREATE TABLE FINE (
    fine_id INT AUTO_INCREMENT,
    amount DECIMAL(8, 2) NOT NULL,
    paid_status ENUM('Unpaid', 'Paid', 'Waived') NOT NULL DEFAULT 'Unpaid',
    lending_id INT NOT NULL UNIQUE,
    CONSTRAINT pk_fine PRIMARY KEY (fine_id),
    CONSTRAINT fk_fine_lending FOREIGN KEY (lending_id) 
        REFERENCES LENDING_RECORD(lending_id) 
        ON DELETE RESTRICT 
        ON UPDATE CASCADE,
    CONSTRAINT chk_fine_amount CHECK (amount >= 0.00)
) ENGINE=InnoDB;

-- =============================================================================
-- TABLE 16: DAMAGE_FINE (Subclass of FINE)
-- =============================================================================
CREATE TABLE DAMAGE_FINE (
    fine_id INT NOT NULL,
    damage_note TEXT NOT NULL,
    CONSTRAINT pk_damage_fine PRIMARY KEY (fine_id),
    CONSTRAINT fk_damage_fine_fine FOREIGN KEY (fine_id) 
        REFERENCES FINE(fine_id) 
        ON DELETE CASCADE 
        ON UPDATE CASCADE
) ENGINE=InnoDB;

-- =============================================================================
-- TABLE 17: OVERDUE_FINE (Subclass of FINE)
-- =============================================================================
CREATE TABLE OVERDUE_FINE (
    fine_id INT NOT NULL,
    days_overdue INT NOT NULL,
    CONSTRAINT pk_overdue_fine PRIMARY KEY (fine_id),
    CONSTRAINT fk_overdue_fine_fine FOREIGN KEY (fine_id) 
        REFERENCES FINE(fine_id) 
        ON DELETE CASCADE 
        ON UPDATE CASCADE,
    CONSTRAINT chk_days_overdue CHECK (days_overdue > 0)
) ENGINE=InnoDB;

-- =============================================================================
-- Performance Indexes for Foreign Keys and Lookups
-- =============================================================================
CREATE INDEX idx_book_category ON BOOK(category_id);
CREATE INDEX idx_book_title ON BOOK(title);
CREATE INDEX idx_lending_student ON LENDING_RECORD(student_id);
CREATE INDEX idx_lending_book ON LENDING_RECORD(book_id);
CREATE INDEX idx_lending_admin ON LENDING_RECORD(admin_id);
CREATE INDEX idx_lending_status ON LENDING_RECORD(status);
CREATE INDEX idx_fine_lending ON FINE(lending_id);
CREATE INDEX idx_reserves_book ON RESERVES(book_id);
CREATE INDEX idx_report_admin ON REPORT(admin_id);
